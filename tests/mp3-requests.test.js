 assert.equal((await post(admin,`/api/admin/mp3-requests/${other.body.request.id}/sent`)).status,200);
 assert.equal((await post(admin,`/api/admin/mp3-requests/${other.body.request.id}/sent`)).status,200);
 assert.equal((await post(admin,`/api/admin/mp3-requests/${other.body.request.id}/refund`)).status,409);
 assert.equal((await q("SELECT * FROM mp3_requests WHERE status='sent'")).length,1);
