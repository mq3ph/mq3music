 const q=async(sql,p)=>(await db.query(sql,p)).rows;
 const app=createApp({env:{APP_URL:origin,SESSION_SECRET:secret,ADMIN_PASSWORD_HASH:passwordHash('test-password')},query:q});
 const id='657e28fc-df67-4dd1-be2d-24bfaa952503',mp3='757e28fc-df67-4dd1-be2d-24bfaa952503',uid='857e28fc-df67-4dd1-be2d-24bfaa952503';
 await q("INSERT INTO songs(id,title,category,published,suno_url) VALUES($1,'Moses','NAME SONGS',true,$2)",[id,link]);
